"""急症前置硬规则（Fix: 项目原先没有急症处置链路）

背景
----
原实现里"急症"只存在于 **prompt 文本**中——[multi_agent/prompts.py:40,49] 让 safety_agent
在回答**生成完之后**补一句"建议及时就医"。这意味着用户说"我呼吸困难"时，系统仍会走完
整条多 Agent 链路（supervisor 规划 → 并行取数 → 综合 → 安全门卫，实测端到端 47.9s、
9 次 LLM 调用），最后才给出一段泛泛的说明。医疗场景下这是不可接受的：

  1. 急症的第一响应必须是"立刻就医"，不能排在 47 秒的 LLM 流水线之后；
  2. 急症判断不能交给 LLM（会漏、会漂移），必须走确定性规则。

设计原则（与项目其它"关键路径不交给 LLM"的做法一致，如 force_patient 强制查病历）
------------------------------------------------------------------------
  1. **纯规则匹配**（字符串包含），零 LLM、零延迟；
  2. **命中即短路整张 LangGraph 图**，直接返回急诊指引，不写 checkpoint；
  3. 词表只收**高精度**表述（收"呼吸困难"而非"胸闷"），宁可少报，也不误报
     打断正常问答——误报的代价是用户被挡在一次正常咨询之外。

已知取舍
--------
  * 否定语境会误报（"我上次胸痛，现在好了"也会命中）。医疗场景按"宁可多提醒一次"
    处理，属安全侧偏置；若要进一步降误报，可在关键词前做窗口内的否定词/时态检测。
  * 命中轮次不落 checkpoint、不进对话历史，避免污染病历上下文。
"""

from typing import List, Optional, Tuple

# ===== 急症规则表：分类 → 高精度关键词 =====
# 只收录"出现即按急症处置"的表述；泛化词（胸闷、头晕、肚子疼）刻意不收。
_EMERGENCY_RULES: List[Tuple[str, Tuple[str, ...]]] = [
    ("呼吸急症", ("呼吸困难", "喘不上气", "喘不过气", "窒息", "呼吸急促", "憋得慌")),
    ("心血管急症", ("胸痛", "胸口剧痛", "心绞痛", "心肌梗死", "心梗")),
    ("意识障碍", ("昏迷", "意识不清", "意识模糊", "叫不醒", "抽搐", "晕厥", "昏倒")),
    ("大出血", ("大出血", "呕血", "咯血", "吐血", "血流不止", "大量出血")),
    ("严重过敏", ("过敏性休克", "喉头水肿", "全身皮疹伴呼吸困难")),
    ("中毒", ("中毒", "误服", "吃错药", "农药")),
    ("自伤风险", ("自杀", "轻生", "不想活", "结束生命", "自残")),
]

# ===== 急诊指引模板（纯文本，不经 LLM）=====
EMERGENCY_RESPONSE_TEMPLATE = """⚠️ 您描述的情况可能属于**急症**，我不能在这里继续为您做分析。

**请立即采取以下行动：**
1. **马上拨打 120 急救电话**，或由他人陪同尽快前往最近的**急诊科**；
2. 不要自行驾车前往，也不要独自等待观察；
3. 保持电话畅通，把症状出现的时间与变化过程告诉急救人员；
4. 如手边有正在服用的药物清单，一并带给医生查看。

{extra}以上信息仅供参考，不能替代医生的当面诊查。"""

# 自伤风险追加段落。刻意不写具体热线号码（号码会变更，写错反而有害），
# 改为指向确定可达的公共求助渠道。
_SELF_HARM_EXTRA = """**如果您或身边的人有伤害自己的想法：**
- 请立刻联系身边信任的人陪伴您，不要独处；
- 也可拨打 120 / 110 求助，或拨打 12345 市民热线询问当地心理援助热线的号码。

"""


def detect_emergency(text: str) -> Optional[str]:
    """检测文本是否命中急症关键词

    Args:
        text: 用户输入（human_input）

    Returns:
        命中的急症分类名（如"呼吸急症"）；未命中返回 None
    """
    if not text:
        return None
    normalized = str(text).strip()
    if not normalized:
        return None

    for category, keywords in _EMERGENCY_RULES:
        for kw in keywords:
            if kw in normalized:
                return category
    return None


def emergency_reply(category: Optional[str] = None) -> str:
    """按分类生成急诊指引文本

    Args:
        category: detect_emergency 返回的分类名（None / 未知分类也返回通用指引）

    Returns:
        可直接返回给用户的急症提示文本
    """
    extra = _SELF_HARM_EXTRA if category == "自伤风险" else ""
    return EMERGENCY_RESPONSE_TEMPLATE.format(extra=extra)
